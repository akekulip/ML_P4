"""W8 step 1 (offline): model, Tofino table entries, generated TNA program and replay queries.

Tree: data-plane DT, grouped split seed 0, depth 10 (the deepest depth whose thermometer key width
fits the 440-bit ternary budget; depth 12 needs 602 bits). Class weight chosen on validation.
Outputs in hw/build/:
  model.json        per-feature fine/coarse entries, leaf entries (ternary value/mask per feature),
                    per-leaf key ranges (controller leaf lookup), tree info
  tree.bin          node arrays for the C CPU backend on Hulk
  queries_<slice>.bin / expected_<slice>.npz   replay queries (the W5 slices) and expected answers
  mvm_tna.p4        generated TNA program (code widths depend on the model)
Also checks offline that the emulated switch path equals tree.apply on every replay query.
"""

from __future__ import annotations

import json
import struct
from pathlib import Path

import numpy as np
from sklearn.tree import DecisionTreeClassifier

from mvm.features import FEATURE_SETS, TreeEncoder, columns_needed
from mvm.leaves import extract_leaf_boxes
from mvm.metrics import binary_metrics
from mvm.p4encode import box_key_ranges, f32_key
from mvm.splits import build_keys, load_rows, replay_order, sample_pools
from mvm.tofino_encode import TofinoEncoding

ROOT = Path(__file__).resolve().parents[1]
PQ, OUT = ROOT / "data/processed/network", ROOT / "hw/build"
DEPTH, SEED, KEY_BUDGET = 10, 0, 440
DP_VISION, DP_HULK = 9, 10
N_SIDE = 15_000


def boundary_slice(keys, order, mask_rows, new_day):
    sub = order[mask_rows]
    day = keys.day.to_numpy()[sub].astype(str)
    b = int(np.argmax(day == new_day))
    assert day[b] == new_day and b > 0
    return sub[b - N_SIDE: b + N_SIDE]


def slice_rows(keys, gidx, columns):
    import pandas as pd
    k = keys.iloc[gidx][["file_idx", "row_in_file"]].reset_index(drop=True)
    parts = [pd.read_parquet(PQ / f"Network_dataset_{int(f)}.parquet", columns=columns).iloc[g.row_in_file.to_numpy()].set_axis(g.index)
             for f, g in k.groupby("file_idx")]
    return pd.concat(parts).sort_index()


def gen_p4(enc: TofinoEncoding, sizes: dict) -> str:
    feats = [ft for ft in enc.features if ft.width > 0]
    meta = "\n".join(f"    bit<{ft.width}> code{ft.index};" for ft in feats)
    tables, applies, leaf_keys = [], [], []
    for ft in feats:
        i, w = ft.index, ft.width
        tables.append(f"""
    action set_code{i}(bit<{w}> c) {{ md.code{i} = c; }}
    table fine{i} {{
        key = {{ hdr.mvm.f{i}[31:12] : exact @name("f{i}_hi"); hdr.mvm.f{i}[11:0] : range @name("f{i}_lo"); }}
        actions = {{ set_code{i}; NoAction; }}
        default_action = NoAction();
        size = {sizes[f'fine{i}']};
    }}
    table coarse{i} {{
        key = {{ hdr.mvm.f{i}[31:12] : range @name("f{i}_hi"); }}
        actions = {{ set_code{i}; NoAction; }}
        default_action = NoAction();
        size = {sizes[f'coarse{i}']};
    }}""")
        applies.append(f"            if (!fine{i}.apply().hit) {{ coarse{i}.apply(); }}")
        leaf_keys.append(f"md.code{i} : ternary;")
    return TNA_TEMPLATE.format(meta=meta, tables="".join(tables), applies="\n".join(applies),
                               leaf_keys=" ".join(leaf_keys), leaf_size=sizes["leaf"],
                               dp_vision=DP_VISION, dp_hulk=DP_HULK)


TNA_TEMPLATE = r"""/* MVM-Lite on Tofino-1 (TNA). GENERATED by experiments/w8_prepare.py -- do not edit by hand.
 * Queries: Ethernet/IPv4/UDP(dst 50000)/mvm from Vision (dev port {dp_vision}).
 * Per feature: fine table (key[31:12] exact, key[11:0] range) then coarse table (key[31:12] range)
 * write a thermometer code; leaf_tbl (ternary over the codes) holds the resident leaves, one entry
 * per leaf. Hit: answer reflected to Vision. Miss: forwarded to Hulk (dev port {dp_hulk}) for CPU
 * inference and digested to the controller. Hulk's replies are forwarded back to Vision.
 * Range keys are at most 20 bits per table (bf-p4c constraint class 2).
 */
#include <core.p4>
#include <tna.p4>

const bit<16> ETH_IPV4 = 0x0800;
const bit<8>  IP_UDP = 17;
const bit<16> MVM_PORT = 50000;

header ethernet_h {{ bit<48> dst; bit<48> src; bit<16> ether_type; }}
header ipv4_h {{
    bit<4> version; bit<4> ihl; bit<8> diffserv; bit<16> total_len; bit<16> identification;
    bit<3> flags; bit<13> frag_offset; bit<8> ttl; bit<8> protocol; bit<16> hdr_checksum;
    bit<32> src_addr; bit<32> dst_addr;
}}
header udp_h {{ bit<16> src_port; bit<16> dst_port; bit<16> len; bit<16> checksum; }}
header mvm_h {{
    bit<32> qid;
    bit<8>  flags;      // bit0 = hit in switch, bit1 = answered by Hulk (CPU)
    bit<8>  klass;
    bit<16> leaf;
    bit<32> t_in;       // ingress MAC timestamp (low 32 bits, ns)
    bit<32> t_pipe;     // egress global timestamp - t_in (ns)
    bit<32> f0; bit<32> f1; bit<32> f2; bit<32> f3; bit<32> f4;
    bit<32> f5; bit<32> f6; bit<32> f7; bit<32> f8; bit<32> f9;
}}

struct headers_t {{ ethernet_h eth; ipv4_h ipv4; udp_h udp; mvm_h mvm; }}

struct digest_t {{
    bit<32> qid;
    bit<32> f0; bit<32> f1; bit<32> f2; bit<32> f3; bit<32> f4;
    bit<32> f5; bit<32> f6; bit<32> f7; bit<32> f8; bit<32> f9;
}}

struct ig_md_t {{
{meta}
}}
struct eg_md_t {{ }}

parser IgParser(packet_in pkt, out headers_t hdr, out ig_md_t md, out ingress_intrinsic_metadata_t ig_intr_md) {{
    state start {{
        pkt.extract(ig_intr_md);
        pkt.advance(PORT_METADATA_SIZE);
        transition parse_eth;
    }}
    state parse_eth {{
        pkt.extract(hdr.eth);
        transition select(hdr.eth.ether_type) {{ ETH_IPV4: parse_ipv4; default: accept; }}
    }}
    state parse_ipv4 {{
        pkt.extract(hdr.ipv4);
        transition select(hdr.ipv4.protocol) {{ IP_UDP: parse_udp; default: accept; }}
    }}
    state parse_udp {{
        pkt.extract(hdr.udp);
        transition select(hdr.udp.dst_port) {{ MVM_PORT: parse_mvm; default: accept; }}
    }}
    state parse_mvm {{
        pkt.extract(hdr.mvm);
        transition accept;
    }}
}}

control Ingress(inout headers_t hdr, inout ig_md_t md,
                in ingress_intrinsic_metadata_t ig_intr_md,
                in ingress_intrinsic_metadata_from_parser_t ig_prsr_md,
                inout ingress_intrinsic_metadata_for_deparser_t ig_dprsr_md,
                inout ingress_intrinsic_metadata_for_tm_t ig_tm_md) {{

    DirectCounter<bit<32>>(CounterType_t.PACKETS) leaf_ctr;
{tables}

    action leaf_hit(bit<16> leaf, bit<8> klass) {{
        // reflect to the sender with swapped MACs: a NIC drops frames whose source MAC is its own
        bit<48> sender = hdr.eth.src;
        hdr.eth.src = hdr.eth.dst;
        hdr.eth.dst = sender;
        hdr.mvm.flags = 1;
        hdr.mvm.klass = klass;
        hdr.mvm.leaf = leaf;
        ig_tm_md.ucast_egress_port = {dp_vision};
        leaf_ctr.count();
    }}
    action leaf_miss() {{
        hdr.mvm.flags = 0;
        ig_tm_md.ucast_egress_port = {dp_hulk};
        ig_dprsr_md.digest_type = 1;
        leaf_ctr.count();   // direct counters must run in every action of the table (bf-p4c rule)
    }}
    table leaf_tbl {{
        key = {{ {leaf_keys} }}
        actions = {{ leaf_hit; leaf_miss; }}
        default_action = leaf_miss();
        counters = leaf_ctr;
        size = {leaf_size};
    }}

    action fwd(PortId_t port) {{ ig_tm_md.ucast_egress_port = port; }}
    table port_fwd {{
        key = {{ ig_intr_md.ingress_port : exact; }}
        actions = {{ fwd; NoAction; }}
        default_action = NoAction();
        size = 16;
    }}

    apply {{
        if (hdr.mvm.isValid() && ig_intr_md.ingress_port == {dp_vision}) {{
            hdr.mvm.t_in = ig_intr_md.ingress_mac_tstamp[31:0];
{applies}
            leaf_tbl.apply();
        }} else {{
            port_fwd.apply();   // Hulk -> Vision replies and ordinary traffic between the two hosts
        }}
    }}
}}

control IgDeparser(packet_out pkt, inout headers_t hdr, in ig_md_t md,
                   in ingress_intrinsic_metadata_for_deparser_t ig_dprsr_md) {{
    Digest<digest_t>() miss_digest;
    apply {{
        if (ig_dprsr_md.digest_type == 1) {{
            miss_digest.pack({{hdr.mvm.qid, hdr.mvm.f0, hdr.mvm.f1, hdr.mvm.f2, hdr.mvm.f3, hdr.mvm.f4,
                              hdr.mvm.f5, hdr.mvm.f6, hdr.mvm.f7, hdr.mvm.f8, hdr.mvm.f9}});
        }}
        pkt.emit(hdr);
    }}
}}

parser EgParser(packet_in pkt, out headers_t hdr, out eg_md_t md, out egress_intrinsic_metadata_t eg_intr_md) {{
    state start {{
        pkt.extract(eg_intr_md);
        transition parse_eth;
    }}
    state parse_eth {{
        pkt.extract(hdr.eth);
        transition select(hdr.eth.ether_type) {{ ETH_IPV4: parse_ipv4; default: accept; }}
    }}
    state parse_ipv4 {{
        pkt.extract(hdr.ipv4);
        transition select(hdr.ipv4.protocol) {{ IP_UDP: parse_udp; default: accept; }}
    }}
    state parse_udp {{
        pkt.extract(hdr.udp);
        transition select(hdr.udp.dst_port) {{ MVM_PORT: parse_mvm; default: accept; }}
    }}
    state parse_mvm {{
        pkt.extract(hdr.mvm);
        transition accept;
    }}
}}

control Egress(inout headers_t hdr, inout eg_md_t md,
               in egress_intrinsic_metadata_t eg_intr_md,
               in egress_intrinsic_metadata_from_parser_t eg_prsr_md,
               inout egress_intrinsic_metadata_for_deparser_t eg_dprsr_md,
               inout egress_intrinsic_metadata_for_output_port_t eg_oport_md) {{
    apply {{
        if (hdr.mvm.isValid() && hdr.mvm.flags == 1) {{
            hdr.mvm.t_pipe = eg_prsr_md.global_tstamp[31:0] - hdr.mvm.t_in;
        }}
    }}
}}

control EgDeparser(packet_out pkt, inout headers_t hdr, in eg_md_t md,
                   in egress_intrinsic_metadata_for_deparser_t eg_dprsr_md) {{
    apply {{ pkt.emit(hdr); }}
}}

Pipeline(IgParser(), Ingress(), IgDeparser(), EgParser(), Egress(), EgDeparser()) pipe;
Switch(pipe) main;
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    keys = build_keys(PQ, ROOT / "data/processed/keys.parquet")
    pools, replay = sample_pools(keys, "grouped", SEED)
    fs = FEATURE_SETS["dp"]
    rows = load_rows(PQ, pools, columns_needed(fs))
    tr, va, te = (rows[rows.pool == p] for p in ("train", "val", "test"))
    enc = TreeEncoder(fs).fit(tr, tr.label.to_numpy())
    Xtr, Xva, Xte = enc.transform(tr), enc.transform(va), enc.transform(te)
    tree = max((DecisionTreeClassifier(max_depth=DEPTH, class_weight=cw, random_state=SEED).fit(Xtr, tr.label) for cw in (None, "balanced")),
               key=lambda m: binary_metrics(va.label.to_numpy(), m.predict(Xva))["macro_f1"])
    te_enc = TofinoEncoding(tree)
    assert te_enc.key_width() <= KEY_BUDGET, te_enc.key_width()
    info = {"depth": DEPTH, "class_weight": str(tree.class_weight), "n_leaves": int(tree.get_n_leaves()),
            "key_width": te_enc.key_width(), "coarse_entries": te_enc.n_coarse_entries(), "fine_entries": te_enc.n_fine_entries(),
            "val_macro_f1": binary_metrics(va.label.to_numpy(), tree.predict(Xva))["macro_f1"],
            "test_macro_f1": binary_metrics(te.label.to_numpy(), tree.predict(Xte))["macro_f1"]}

    # model.json for the controller
    boxes = {b.leaf_id: b for b in extract_leaf_boxes(tree)}
    leaves = []
    for e in te_enc.leaf_entries():
        lo, hi = box_key_ranges(boxes[e["leaf_id"]])
        leaves.append({"leaf_id": e["leaf_id"], "klass": e["klass"],
                       "tern": [[int(v), int(m)] for v, m in e["per_feature"]],
                       "key_lo": [int(x) for x in lo], "key_hi": [int(x) for x in hi]})
    feats = [{"index": ft.index, "width": ft.width,
              "fine": [[int(b), int(lo), int(hi), int(c)] for b, lo, hi, c in ft.fine],
              "coarse": [[int(lo), int(hi), int(c)] for lo, hi, c in ft.coarse]} for ft in te_enc.features]
    (OUT / "model.json").write_text(json.dumps({"info": info, "features": feats, "leaves": leaves}))

    # tree.bin for the C backend: n_nodes, then per node feature(i32) threshold(f64) left(i32) right(i32) klass(i32)
    t = tree.tree_
    klass = tree.classes_[np.argmax(t.value[:, 0, :], axis=1)].astype(np.int32)
    with open(OUT / "tree.bin", "wb") as fh:
        fh.write(struct.pack("<i", t.node_count))
        for n in range(t.node_count):
            fh.write(struct.pack("<idiii", int(t.feature[n]), float(t.threshold[n]), int(t.children_left[n]),
                                 int(t.children_right[n]), int(klass[n])))

    # replay queries (the W5 slices) with expected answers, plus the offline emulated-switch check
    order = replay_order(keys, replay)
    label = keys.label.to_numpy()[order]
    slices = {"full_0425_to_0426": boundary_slice(keys, order, np.ones(len(order), bool), "2019-04-26"),
              "benign_0427_to_0428": boundary_slice(keys, order, label == 0, "2019-04-28")}
    cols = columns_needed(fs)
    for name, g in slices.items():
        X = enc.transform(slice_rows(keys, g, cols))
        k32 = f32_key(X)
        leaf_true, pred_true = tree.apply(X), tree.predict(X)
        codes = te_enc.codes_like_switch(k32)
        emu = np.full(len(X), -1)
        for e in te_enc.leaf_entries():
            emu[np.all((codes & e["mask"]) == e["value"], axis=1)] = e["leaf_id"]
        assert np.array_equal(emu, leaf_true), f"emulated switch differs from tree.apply on {name}"
        qid = np.arange(len(X), dtype=np.uint32)
        np.hstack([qid[:, None], k32.astype(np.uint32)]).astype("<u4").tofile(OUT / f"queries_{name}.bin")
        np.savez(OUT / f"expected_{name}.npz", leaf=leaf_true, klass=pred_true, gidx=g)
        info[f"slice_{name}"] = len(X)
    # a range entry occupies several TCAM rows (nibble-wise range encoding): fine0 held only 173 of
    # 198 entries in 256 rows on hardware, so size range tables at 4x their entry count
    sizes = {f"fine{ft.index}": max(64, 1 << (4 * len(ft.fine) - 1).bit_length()) for ft in te_enc.features}
    sizes |= {f"coarse{ft.index}": max(64, 1 << (4 * len(ft.coarse) - 1).bit_length()) for ft in te_enc.features}
    sizes["leaf"] = 64
    (OUT / "mvm_tna.p4").write_text(gen_p4(te_enc, sizes))
    (OUT / "info.json").write_text(json.dumps(info, indent=1))
    print(json.dumps(info, indent=1))


if __name__ == "__main__":
    main()
